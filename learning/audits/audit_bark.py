"""The Bark arm of the vowel audit: formant space vs the hand-placed space.

Run from the repo root (or anywhere):

    python learning/audits/audit_bark.py

``audit_feature_space.py`` asks one question: does our hand-placed vowel
quadrilateral *order* vowel pairs the way rappers' rhyme choices do
(Hirjee & Brown 2009's log-odds)? This script asks the same question of a
competitor: Bark-scaled formant space, built from Hillenbrand et al.
(1995)'s measurements of American English vowels. The quadrilateral is a
diagram of where the tongue goes; formant space in Bark is the standard
model of how vowels *sound*. Neither was fitted to rhyme, so both are
fair candidates for predicting it.

Why *rank* comparison, again: log-odds entangle similarity with a
frequency correction, so their absolute values are on no scale of ours.
Bark distances are not on our [0, 1] scale either. Spearman's ρ compares
only the two orderings, which is the one thing all three sources share.

**Only 12 vowels.** Hillenbrand recorded 12 /hVd/ vowels and no AY, AW or
OY, so every number here covers the 66 pairs of those 12. The hand space
is restricted to the same pairs for a like-for-like ρ (+0.561 here, vs
+0.51 over all 15 vowels in ``audit_feature_space.py``).

**Distance in a condition.** A single-time-point condition uses plain
Euclidean distance between the two vowels' mean Bark vectors. A
two-time-point condition (20% and 80% of the vowel) averages the distance
at 20% with the distance at 80%, the way ``features.vowel_distance``
averages a diphthong's start and end distances.

This is an **audit, not tuning**: nothing in ``features.py`` moves. The
findings are tuning-ledger item 13. A runnable Bark space for the Unit
14 sweep waits on formant data for AY, AW and OY (see the ledger).

The Bark means come from ``hillenbrand_1995_bark.py``, generated by
``derive_hillenbrand_bark.py`` (see it for provenance).
"""

from __future__ import annotations

import math
import random
import sys
from itertools import combinations
from pathlib import Path
from statistics import mean

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from audit_feature_space import _ranks, rank_report, spearman  # noqa: E402
from coraal_dcb_stella_bark import MEANS as AAE_MEANS  # noqa: E402
from hillenbrand_1995_bark import CONDITIONS  # noqa: E402
from hirjee_brown_2009 import VOWEL_LOGODDS  # noqa: E402

from rhyme_schemer.features import vowel_similarity  # noqa: E402

VOWELS = sorted(CONDITIONS["t20_80_f1f2_men"])

LABELS = {
    "steady_f1f2_men": "Bark F1/F2, steady state, men",
    "t20_80_f1f2_men": "Bark F1/F2 @20%+80%, men",
    "t20_80_f1f2f3_men": "Bark F1/F2/F3 @20%+80%, men",
    "lobanov_t20_80_f1f2_men_women": "Lobanov-Bark F1/F2 @20%+80%, men+women",
    "lobanov_t20_80_f1f2f3_men_women": "Lobanov-Bark F1/F2/F3 @20%+80%, men+women",
}

# The audit's best condition, which the bootstrap compares with the hand space.
BEST = "t20_80_f1f2_men"

# Pairs the ledger names, printed with their rank under every condition.
NAMED_PAIRS = [
    ("EY", "IH"), ("EH", "EY"), ("EH", "IH"), ("EH", "IY"), ("AA", "AO"),
    ("AA", "AH"), ("AH", "ER"), ("AA", "ER"), ("AO", "ER"), ("ER", "UH"),
    ("ER", "OW"), ("AE", "EH"), ("IH", "IY"), ("UH", "UW"),
]


def formant_distance(table: dict, a: str, b: str) -> float:
    """Mean over time points of the Euclidean distance between a and b."""
    return mean(math.dist(p, q) for p, q in zip(table[a], table[b]))


def bootstrap_difference(ours, theirs, corpus, resamples=2000, seed=0):
    """Resample the pairs; return sorted ρ(theirs) - ρ(ours) differences.

    Resampling *pairs* treats them as independent, which they aren't: each
    vowel appears in 11 of the 66 pairs. So the interval this yields is
    optimistic, narrower than the truth.
    """
    rng = random.Random(seed)
    n = len(corpus)
    diffs = []
    for _ in range(resamples):
        idx = [rng.randrange(n) for _ in range(n)]
        pick = lambda xs: [xs[i] for i in idx]  # noqa: E731
        try:
            diffs.append(
                spearman(pick(theirs), pick(corpus)) - spearman(pick(ours), pick(corpus))
            )
        except ZeroDivisionError:  # a resample with every value tied
            pass
    return sorted(diffs)


def main() -> None:
    pairs = list(combinations(VOWELS, 2))
    corpus = [VOWEL_LOGODDS[a, b] for a, b in pairs]
    hand = [vowel_similarity(a, b) for a, b in pairs]
    # Negated distance, so that "larger = more similar" holds for every
    # column, as _ranks and rank_report expect.
    bark = {
        name: [-formant_distance(table, a, b) for a, b in pairs]
        for name, table in CONDITIONS.items()
    }

    print(f"{len(pairs)} pairs over the 12 vowels Hillenbrand and H&B share:")
    print(f"  {' '.join(VOWELS)}")
    print("\nSpearman rho against Hirjee & Brown 2009 vowel log-odds:")
    print(f"  {'hand-placed quadrilateral (features.py)':<44} rho = {spearman(hand, corpus):+.3f}")
    for name, sims in bark.items():
        print(f"  {LABELS[name]:<44} rho = {spearman(sims, corpus):+.3f}")

    rank_report(
        f"VOWELS: {LABELS[BEST]} vs Hirjee & Brown 2009 (similarity = -Bark distance)",
        pairs, bark[BEST], corpus,
    )

    columns = [("hand", hand)] + [(str(i), bark[name]) for i, name in enumerate(bark, 1)]
    ranks = [_ranks(values) for _, values in columns]
    corpus_ranks = _ranks(corpus)
    print("\nnamed pairs, rank under each space (1 = most similar of 66):")
    for i, name in enumerate(bark, 1):
        print(f"  {i} = {LABELS[name]}")
    header = " ".join(f"{label:>4}" for label, _ in columns)
    print(f"  {'pair':<7} {header}  {'H&B':>4}  log-odds")
    for a, b in NAMED_PAIRS:
        i = pairs.index(tuple(sorted((a, b))))
        row = " ".join(f"{r[i]:>4.0f}" for r in ranks)
        print(f"  {a + '~' + b:<7} {row}  {corpus_ranks[i]:>4.0f}  {corpus[i]:+.1f}")

    diffs = bootstrap_difference(hand, bark[BEST], corpus)
    print(
        f"\nbootstrap over pairs, rho({LABELS[BEST]}) - rho(hand):\n"
        f"  median {diffs[len(diffs) // 2]:+.3f}, 95% CI "
        f"[{diffs[int(0.025 * len(diffs))]:+.3f}, {diffs[int(0.975 * len(diffs))]:+.3f}]"
        "  (optimistic: pairs share vowels)"
    )



# Pairs whose ranks the AAE arm reports. The first group tests the dialect
# finding and the item-13 suspects on vowels Hillenbrand also covers; the
# second involves AY and OY, which only the AAE data has.
AAE_SHARED_PAIRS = [
    ("AE", "EH"), ("EY", "IH"), ("EH", "IH"), ("AA", "AO"), ("AA", "AH"),
    ("AH", "ER"), ("AA", "ER"), ("AO", "ER"), ("ER", "OW"), ("IH", "IY"),
]
AAE_DIPHTHONG_PAIRS = [
    ("AA", "AY"), ("AE", "AY"), ("AH", "AY"), ("AY", "EH"), ("AY", "EY"),
    ("AY", "IY"), ("AY", "OY"), ("AO", "OY"), ("OW", "OY"),
]


def aae_arm() -> None:
    """Proof of concept: the same comparison with AAE reference data.

    ``coraal_dcb_stella_bark.py`` holds Bark means from 16 Washington DC men
    reading a short passage (CORAAL; see ``derive_coraal_stella_bark.py``).
    It covers 13 vowels: no AW (not in the passage) and no UH (one token).
    Two comparisons, because the vowel sets differ:

    1. The 11 vowels all three spaces share (55 pairs): hand vs Hillenbrand
       vs AAE, like for like. Ledger item 13d predicts the AAE data should
       not make AE~EH the closest pair, as Hillenbrand's Michigan data does.
    2. All 13 AAE vowels (78 pairs), including AY and OY, which Hillenbrand
       lacks: hand vs AAE only.
    """
    print("\n\n==== AAE arm (proof of concept): CORAAL DC read passage, men ====")
    corpus_of = lambda ps: [VOWEL_LOGODDS[a, b] for a, b in ps]  # noqa: E731
    hand_of = lambda ps: [vowel_similarity(a, b) for a, b in ps]  # noqa: E731
    aae_of = lambda ps: [-formant_distance(AAE_MEANS, a, b) for a, b in ps]  # noqa: E731

    shared = sorted(set(AAE_MEANS) & set(CONDITIONS[BEST]))
    pairs = list(combinations(shared, 2))
    corpus, hand, aae = corpus_of(pairs), hand_of(pairs), aae_of(pairs)
    hill = [-formant_distance(CONDITIONS[BEST], a, b) for a, b in pairs]
    print(f"\n{len(pairs)} pairs over the {len(shared)} vowels all three share:")
    print(f"  {' '.join(shared)}")
    print(f"  {'hand-placed quadrilateral':<44} rho = {spearman(hand, corpus):+.3f}")
    print(f"  {'Hillenbrand ' + LABELS[BEST]:<44} rho = {spearman(hill, corpus):+.3f}")
    print(f"  {'AAE (CORAAL) Bark F1/F2 @20%+80%, men':<44} rho = {spearman(aae, corpus):+.3f}")
    ranks = [_ranks(hand), _ranks(hill), _ranks(aae), _ranks(corpus)]
    print(f"\n  rank of {len(pairs)} (1 = most similar):")
    print(f"  {'pair':<7} {'hand':>4} {'Hill':>4} {'AAE':>4}  {'H&B':>4}  log-odds")
    for a, b in AAE_SHARED_PAIRS:
        i = pairs.index((a, b))
        row = " ".join(f"{r[i]:>4.0f}" for r in ranks[:3])
        print(f"  {a + '~' + b:<7} {row}  {ranks[3][i]:>4.0f}  {corpus[i]:+.1f}")

    full = sorted(AAE_MEANS)
    pairs = list(combinations(full, 2))
    corpus, hand, aae = corpus_of(pairs), hand_of(pairs), aae_of(pairs)
    print(f"\n{len(pairs)} pairs over all {len(full)} AAE vowels (adds AY, OY):")
    print(f"  {'hand-placed quadrilateral':<44} rho = {spearman(hand, corpus):+.3f}")
    print(f"  {'AAE (CORAAL) Bark F1/F2 @20%+80%, men':<44} rho = {spearman(aae, corpus):+.3f}")
    ranks = [_ranks(hand), _ranks(aae), _ranks(corpus)]
    print(f"\n  rank of {len(pairs)} (1 = most similar):")
    print(f"  {'pair':<7} {'hand':>4} {'AAE':>4}  {'H&B':>4}  log-odds")
    for a, b in AAE_DIPHTHONG_PAIRS:
        i = pairs.index((a, b))
        print(
            f"  {a + '~' + b:<7} {ranks[0][i]:>4.0f} {ranks[1][i]:>4.0f}  "
            f"{ranks[2][i]:>4.0f}  {corpus[i]:+.1f}"
        )
    rank_report(
        "AAE (CORAAL) Bark vs Hirjee & Brown 2009, 13 vowels", pairs, aae, corpus
    )
    diffs = bootstrap_difference(hand, aae, corpus)
    print(
        "\nbootstrap over pairs, rho(AAE) - rho(hand), 13 vowels:\n"
        f"  median {diffs[len(diffs) // 2]:+.3f}, 95% CI "
        f"[{diffs[int(0.025 * len(diffs))]:+.3f}, {diffs[int(0.975 * len(diffs))]:+.3f}]"
        "  (optimistic: pairs share vowels)"
    )


if __name__ == "__main__":
    main()
    aae_arm()
